"""Train a tiny hashed TF-IDF nearest-centroid intent classifier; no network or user records.
This is a domain intent model, not a generative language model. Retrain deterministically.
"""
from collections import Counter
from hashlib import sha256
import json,math,re,unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SIZE=768

def features(text):
    text=unicodedata.normalize('NFKC',text).lower()
    text=re.sub(r'[^\w\s\u0980-\u09ff]',' ',text)
    text=' '.join(text.split())
    words=text.split();terms=['w:'+w for w in words]
    terms+=['b:'+a+' '+b for a,b in zip(words,words[1:])]
    for word in words:
        padded='^'+word+'$'
        terms+=['c:'+padded[i:i+3] for i in range(max(0,len(padded)-2))]
    counts=Counter()
    for term in terms:
        h=2166136261
        for ch in term:
            # Match JS code points; training texts use BMP code points.
            h=((h^ord(ch))*16777619)&0xffffffff
        counts[h%SIZE]+=1
    return counts

def train():
    path=ROOT/'data/local_assistant/intents.json';raw=path.read_bytes();corpus=json.loads(raw)
    examples=[(label,text) for label,texts in corpus.items() for text in texts]
    df=Counter()
    for _,text in examples:df.update(features(text).keys())
    idf=[math.log((1+len(examples))/(1+df[i]))+1 for i in range(SIZE)]
    def vector(text):
        v={i:(1+math.log(count))*idf[i] for i,count in features(text).items()};norm=math.sqrt(sum(x*x for x in v.values()))
        return {i:x/norm for i,x in v.items()} if norm else {}
    weights={}
    for label,texts in corpus.items():
        total=Counter()
        for text in texts:total.update(vector(text))
        norm=math.sqrt(sum(x*x for x in total.values()))
        weights[label]=[[i,round(x/norm,5)] for i,x in sorted(total.items())]
    model=dict(version='local-intents-1',algorithm='hashed TF-IDF nearest centroid',dimensions=SIZE,training_examples=len(examples),training_sha256=sha256(raw).hexdigest(),idf=[round(x,5) for x in idf],weights=weights)
    target=ROOT/'web/src/localModel.ts';target.write_text('// Generated by scripts/train_local_assistant.py. No user data.\nexport const localModel='+json.dumps(model,ensure_ascii=False,separators=(',',':'))+';\n')
    print(json.dumps({'labels':len(corpus),'examples':len(examples),'artifact_bytes':target.stat().st_size,'training_sha256':model['training_sha256']}))
if __name__=='__main__':train()
